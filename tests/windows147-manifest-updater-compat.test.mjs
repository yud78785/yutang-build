import test from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync } from 'node:crypto';
import {
  makeManifest, manifestBytes, signManifest
} from '../tools/windows147-signing/core.mjs';
import {
  UpdateService, verifySignedManifest, validateManifest,
  UPDATE_MANIFEST_NAME, UPDATE_SIGNATURE_NAME
} from '../tools/windows147-update-patched/update-service.mjs';

const THUMB = 'A'.repeat(40);
const VERSION = '1.4.8';
const TAG = 'v' + VERSION;
const NAME = 'Dafeiyu-Douyin-API-' + VERSION + '-win-x64.exe';
const EXE = Buffer.concat([Buffer.from('MZ'),Buffer.alloc(2046,0x5c)]);
const ROOT = 'https://github.com/yud78785/yutang-build/releases/download/' + TAG + '/';
const API = 'https://api.github.com/repos/yud78785/yutang-build/releases/latest';

function fixture() {
  const {publicKey,privateKey} = generateKeyPairSync('ed25519');
  const publicPem = publicKey.export({type:'spki',format:'pem'});
  const privatePem = privateKey.export({type:'pkcs8',format:'pem'});
  const manifest = makeManifest({
    version:VERSION, exeName:NAME, exeBytes:EXE,
    upstreamCommit:'9c49833078f4b4d18b9211ef86d024e7f2e15739',
    patchCommit:'9cc16d7e64d59dc141e9c6687b8dd461934fcc35',
    workflowRunId:60000000001, artifactId:16000000001,
    thumbprint:THUMB, subject:'CN=Mock Personal Signer, C=RS'
  });
  const bytes = manifestBytes(manifest);
  const signature = signManifest(bytes,privatePem);
  const release = {
    draft:false,prerelease:false,tag_name:TAG,
    assets:[
      {name:UPDATE_MANIFEST_NAME,size:bytes.length,browser_download_url:ROOT+UPDATE_MANIFEST_NAME},
      {name:UPDATE_SIGNATURE_NAME,size:Buffer.byteLength(signature),browser_download_url:ROOT+UPDATE_SIGNATURE_NAME},
      {name:NAME,size:EXE.length,browser_download_url:ROOT+NAME}
    ]
  };
  return {bytes,signature,manifest,publicPem,privatePem,release};
}

function mockedFetch({release,bytes,signature},observed) {
  return async (url) => {
    observed.push(url);
    if(url===API)return new Response(JSON.stringify(release),{status:200});
    if(url===ROOT+UPDATE_MANIFEST_NAME)return new Response(bytes,{status:200});
    if(url===ROOT+UPDATE_SIGNATURE_NAME)return new Response(signature,{status:200});
    throw new Error('UNEXPECTED_NETWORK_REQUEST: '+url);
  };
}

test('exact manifest generated by the signing core passes unchanged updater verifier', () => {
  const f=fixture();
  assert.equal(verifySignedManifest(f.bytes,f.signature,f.publicPem),true);
  assert.deepEqual(validateManifest(f.manifest,{tag:TAG,publisherThumbprint:THUMB}),f.manifest);
});

test('exact updater rejects modified JSON after Ed25519 signing', () => {
  const f=fixture();
  const altered=Buffer.from(f.bytes);
  altered[20]^=1;
  assert.throws(()=>verifySignedManifest(altered,f.signature,f.publicPem),/UPDATE_MANIFEST_SIGNATURE_INVALID/);
});

test('exact updater rejects untrusted or absent Ed25519 public key', () => {
  const f=fixture();
  assert.throws(()=>verifySignedManifest(f.bytes,f.signature,''),/UPDATE_MANIFEST_PUBLIC_KEY_NOT_CONFIGURED/);
  const other=generateKeyPairSync('ed25519').publicKey.export({type:'spki',format:'pem'});
  assert.throws(()=>verifySignedManifest(f.bytes,f.signature,other),/UPDATE_MANIFEST_SIGNATURE_INVALID/);
});

test('publisher, tag and repository mismatch rejected after signature verification', () => {
  const f=fixture();
  assert.throws(()=>validateManifest(f.manifest,{tag:TAG,publisherThumbprint:'B'.repeat(40)}),/UPDATE_MANIFEST_PUBLISHER_MISMATCH/);
  assert.throws(()=>validateManifest(f.manifest,{tag:'v1.4.9',publisherThumbprint:THUMB}),/UPDATE_MANIFEST_IDENTITY_MISMATCH/);
  assert.throws(()=>validateManifest({...f.manifest,repository:'attacker/fork'},{tag:TAG,publisherThumbprint:THUMB}),/UPDATE_MANIFEST_IDENTITY_MISMATCH/);
});

test('mock latest GitHub release check accepts signed manifest without downloading or executing EXE',async () => {
  const f=fixture(),calls=[];
  const service=new UpdateService({
    version:'1.4.7',directory:'/tmp/yutang-updater-integration-test',
    manifestPublicKey:f.publicPem,publisherThumbprint:THUMB,
    fetchImpl:mockedFetch(f,calls),
    verifyAuthenticode:()=>{throw new Error('SHOULD_NOT_CHECK_BINARY_DURING_RELEASE_CHECK');}
  });
  const result=await service.check();
  assert.equal(result.status,'available');
  assert.equal(result.latestVersion,VERSION);
  assert.equal(result.sha256,f.manifest.asset.sha256);
  assert.equal(result.publisherThumbprint,THUMB);
  assert.deepEqual(calls,[API,ROOT+UPDATE_MANIFEST_NAME,ROOT+UPDATE_SIGNATURE_NAME]);
});

test('mock release check fails closed for tampered manifest or wrong pinned publisher',async () => {
  const original=fixture();
  for(const variant of ['tampered','publisher']) {
    const f={...original};
    if(variant==='tampered')f.bytes=Buffer.concat([original.bytes,Buffer.from(' ')]);
    const calls=[];
    const service=new UpdateService({
      version:'1.4.7',directory:'/tmp/yutang-updater-integration-test',
      manifestPublicKey:f.publicPem,publisherThumbprint:variant==='publisher'?'B'.repeat(40):THUMB,
      fetchImpl:mockedFetch(f,calls),
      verifyAuthenticode:()=>{throw new Error('UNEXPECTED_BINARY_EXECUTION');}
    });
    const result=await service.check();
    assert.equal(result.status,'error');
    assert.equal(calls.includes(ROOT+NAME),false);
  }
});
